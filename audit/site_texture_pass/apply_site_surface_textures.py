def get_principled(m):
    if not m.use_nodes: m.use_nodes=True
    return next((n for n in m.node_tree.nodes if n.type=='BSDF_PRINCIPLED'),None)

def texture_material(m,p):
    if not m or not m.node_tree: return 0
    nodes=m.node_tree.nodes; links=m.node_tree.links
    bs=get_principled(m)
    if not bs: return 0
    # Preserve the artist-authored physical color and reflectance values as the baseline.
    base=tuple(float(c) for c in bs.inputs['Base Color'].default_value)
    base_rough=float(bs.inputs['Roughness'].default_value)
    if len(base)<4: base=base+(1.0,)
    # Remove only nodes previously generated by this pass, allowing idempotent reruns.
    for n in list(nodes):
        if n.get('site_texture_pass_v1'):
            nodes.remove(n)
    geo=nodes.new('ShaderNodeNewGeometry'); geo.label='World position in meters'; geo['site_texture_pass_v1']=True
    macro=nodes.new('ShaderNodeTexNoise'); macro.label=f'{p["kind"]} broad variation ({p["macro"]:.2f}/m)'; macro['site_texture_pass_v1']=True
    macro.inputs['Scale'].default_value=p['macro']; macro.inputs['Detail'].default_value=2.0; macro.inputs['Roughness'].default_value=.68
    links.new(geo.outputs['Position'],macro.inputs['Vector'])
    ramp=nodes.new('ShaderNodeValToRGB'); ramp.label='Low contrast authored-color variation'; ramp['site_texture_pass_v1']=True
    lo=tuple(max(0.0,min(1.0,base[i]*(1-p['variation']))) for i in range(3))+(base[3],)
    hi=tuple(max(0.0,min(1.0,base[i]*(1+p['variation']))) for i in range(3))+(base[3],)
    ramp.color_ramp.elements[0].position=.2; ramp.color_ramp.elements[0].color=lo
    ramp.color_ramp.elements[1].position=.8; ramp.color_ramp.elements[1].color=hi
    links.new(macro.outputs['Fac'],ramp.inputs['Fac'])
    grain_variation={'turf':.075,'asphalt':.045,'concrete':.035,'coated asphalt':.04,'brick paving':.05,'brick':.04,'limestone':.035,'thermal granite':.04,'polished granite':.025}.get(p['kind'],.02)
    grain=nodes.new('ShaderNodeTexNoise'); grain.label=f'Fine surface grain ({p["grain"]:.1f}/m)'; grain['site_texture_pass_v1']=True
    grain.inputs['Scale'].default_value=p['grain']; grain.inputs['Detail'].default_value=2.0; grain.inputs['Roughness'].default_value=.72
    links.new(geo.outputs['Position'],grain.inputs['Vector'])
    grain_ramp=nodes.new('ShaderNodeValToRGB'); grain_ramp.label=f'Fine color grain (±{grain_variation:.1%})'; grain_ramp['site_texture_pass_v1']=True
    grain_lo=1.0-grain_variation; grain_hi=1.0+grain_variation
    grain_ramp.color_ramp.elements[0].position=.2; grain_ramp.color_ramp.elements[0].color=(grain_lo,grain_lo,grain_lo,1)
    grain_ramp.color_ramp.elements[1].position=.8; grain_ramp.color_ramp.elements[1].color=(grain_hi,grain_hi,grain_hi,1)
    links.new(grain.outputs['Fac'],grain_ramp.inputs['Fac'])
    colored=nodes.new('ShaderNodeMixRGB'); colored.blend_type='MULTIPLY'; colored.label='Macro color times subtle fine grain'; colored['site_texture_pass_v1']=True
    colored.inputs['Fac'].default_value=1.0
    links.new(ramp.outputs['Color'],colored.inputs[1]); links.new(grain_ramp.outputs['Color'],colored.inputs[2])
    # Add physical joints to paving materials where broad unsegmented planes currently carry them.
    paving_patterns={
        'Plaza_Purdue_Red_Brick_Pavers':(.24,.12,.007,(.96,.92,.87),(.82,.76,.71),(.48,.45,.42)),
        'Sidewalk_Purdue_Brick_Accent':(.24,.12,.007,(.96,.92,.87),(.84,.78,.73),(.50,.46,.43)),
        'SouthHall_Purdue_Red_Brick':(.24,.075,.008,(.96,.91,.86),(.84,.75,.69),(.50,.46,.42)),
        'Plaza_Architectural_Concrete':(3.2,3.2,.016,(.99,.98,.96),(.95,.94,.92),(.74,.72,.69)),
        'Campus_Walkway_Concrete':(2.8,2.8,.015,(.99,.98,.96),(.95,.94,.92),(.74,.72,.69)),
    }
    pattern=paving_patterns.get(m.name)
    if pattern:
        width,row_height,mortar_size,color1,color2,mortar_color=pattern
        tiles=nodes.new('ShaderNodeTexBrick'); tiles.label=f'Physical joint module {width:.2f} × {row_height:.2f} m'; tiles['site_texture_pass_v1']=True
        tiles.inputs['Scale'].default_value=1.0; tiles.inputs['Brick Width'].default_value=width; tiles.inputs['Row Height'].default_value=row_height
        tiles.inputs['Mortar Size'].default_value=mortar_size; tiles.inputs['Mortar Smooth'].default_value=.001
        tiles.inputs['Color1'].default_value=(*color1,1); tiles.inputs['Color2'].default_value=(*color2,1); tiles.inputs['Mortar'].default_value=(*mortar_color,1)
        links.new(geo.outputs['Position'],tiles.inputs['Vector'])
        paver_mix=nodes.new('ShaderNodeMixRGB'); paver_mix.blend_type='MULTIPLY'; paver_mix.label='Tile and mortar tone'; paver_mix['site_texture_pass_v1']=True
        paver_mix.inputs['Fac'].default_value=1.0; links.new(colored.outputs['Color'],paver_mix.inputs[1]); links.new(tiles.outputs['Color'],paver_mix.inputs[2]); links.new(paver_mix.outputs['Color'],bs.inputs['Base Color'])
        m['site_paving_module_m']=(width,row_height); m['site_paving_joint_width_m']=mortar_size
    else:
        links.new(colored.outputs['Color'],bs.inputs['Base Color'])
    bump_noise=nodes.new('ShaderNodeTexNoise'); bump_noise.label=f'Micro-relief ({p["bump_scale"]:.1f}/m)'; bump_noise['site_texture_pass_v1']=True
    bump_noise.inputs['Scale'].default_value=p['bump_scale']; bump_noise.inputs['Detail'].default_value=2.0; bump_noise.inputs['Roughness'].default_value=.7
    links.new(geo.outputs['Position'],bump_noise.inputs['Vector'])
    bump=nodes.new('ShaderNodeBump'); bump.label=f'Subtle {p["kind"]} relief'; bump['site_texture_pass_v1']=True
    bump.inputs['Distance'].default_value=p['bump']; bump.inputs['Strength'].default_value=p['bump_strength']
    links.new(bump_noise.outputs['Fac'],bump.inputs['Height']); links.new(bump.outputs['Normal'],bs.inputs['Normal'])
    # Noise variation in the grain lightly changes roughness at a scale readable in close views.
    rough=nodes.new('ShaderNodeMapRange'); rough.label='Low roughness variation'; rough['site_texture_pass_v1']=True
    rough.clamp=True; rough.inputs['From Min'].default_value=.18; rough.inputs['From Max'].default_value=.82
    rough.inputs['To Min'].default_value=max(.05,p['rough']-p['rough_delta']); rough.inputs['To Max'].default_value=min(1.0,p['rough']+p['rough_delta'])
    links.new(grain.outputs['Fac'],rough.inputs['Value']); links.new(rough.outputs['Result'],bs.inputs['Roughness'])
    m['site_texture_pass']='v1: world-space, meter-scaled procedural surface detail'
    m['site_surface_type']=p['kind']; m['site_surface_macro_scale_per_m']=p['macro']
    m['site_surface_macro_color_variation']=p['variation']; m['site_surface_grain_scale_per_m']=p['grain']; m['site_surface_grain_color_variation']=grain_variation
    m['site_surface_microrelief_m']=p['bump']; m['site_surface_color_preserved']=True
    # viewport swatch stays authored color
    m.diffuse_color=base
    return len([n for n in nodes if n.get('site_texture_pass_v1')])

