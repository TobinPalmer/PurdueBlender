# Correct the surface-facing direction on one-sided road planes. This changes face winding/normals
# only; mesh vertices, UV layers (none on these GIS surfaces), outlines, and placements are untouched.
normal_targets=['Purdue_Road_Asphalt_Surface','Purdue_Elevated_Sidewalks_Wide','Purdue_Intersection_Crosswalk_Stripes','Purdue_Road_Yellow_Striping','Purdue_Dedicated_Green_Bike_Lanes']
normal_fixes=[]
for object_name in normal_targets:
    obj=bpy.data.objects.get(object_name)
    if not obj or obj.type!='MESH': continue
    bm=bmesh.new(); bm.from_mesh(obj.data); flipped=0
    for face in bm.faces:
        if face.normal.z < -0.95:
            face.normal_flip(); flipped+=1
    if flipped:
        bm.normal_update(); bm.to_mesh(obj.data); obj.data.update()
    bm.free()
    normal_fixes.append({'object':object_name,'faces_flipped_up':flipped,'faces_total':len(obj.data.polygons)})
coverage=[]; not_found=[]; no_nodes=[]
for name,p in SURFACES.items():
    m=bpy.data.materials.get(name)
    if not m and name in UNUSED_SOURCE_MATERIALS:
        src=UNUSED_SOURCE_MATERIALS[name]; m=bpy.data.materials.new(name); m.diffuse_color=(*src['color'],1); m.use_nodes=True
        bs=get_principled(m); bs.inputs['Base Color'].default_value=(*src['color'],1); bs.inputs['Roughness'].default_value=src['roughness']; m.use_fake_user=True
    if not m: not_found.append(name); continue
    count=texture_material(m,p)
    objs=[o.name for o in bpy.data.objects if o.type=='MESH' and any(slot==m for slot in o.data.materials)]
    coverage.append({'material':name,'type':p['kind'],'objects':len(objs),'object_names':objs,'nodes_added':count,'base_color_preserved':True,'strength':p})
    if not count: no_nodes.append(name)

