def point_camera(name, eye, target, lens):
    data=bpy.data.cameras.new(name); cam=bpy.data.objects.new(name,data); scene.collection.objects.link(cam)
    cam.location=eye; cam.data.lens=lens; cam.data.clip_end=5000
    cam.rotation_euler=(Vector(target)-cam.location).to_track_quat('-Z','Y').to_euler()
    return cam

def preview(name, object_names, eye, target, lens, size=960):
    for o in scene.objects: o.hide_render=True
    for n in object_names:
        o=bpy.data.objects.get(n)
        if o: o.hide_render=False
    # broad soft daylight fill emphasizes low relief without hard, fake-looking shadows
    lamp_data=bpy.data.lights.new('QA_Softbox_'+name,'AREA'); lamp_data.energy=2400; lamp_data.shape='DISK'; lamp_data.size=30
    lamp=bpy.data.objects.new('QA_Softbox_'+name,lamp_data); scene.collection.objects.link(lamp); lamp.location=(eye[0]+4,eye[1]-5,eye[2]+8)
    lamp.rotation_euler=(Vector(target)-lamp.location).to_track_quat('-Z','Y').to_euler()
    cam=point_camera('QA_Camera_'+name,eye,target,lens); scene.camera=cam
    scene.render.resolution_x=size; scene.render.filepath=str(OUT/f'{name}.png')
    bpy.ops.render.render(write_still=True)
    cam_data=cam.data; bpy.data.objects.remove(cam,do_unlink=True); bpy.data.cameras.remove(cam_data)
    lamp_data=lamp.data; bpy.data.objects.remove(lamp,do_unlink=True); bpy.data.lights.remove(lamp_data)
    return str(OUT/f'{name}.png')

