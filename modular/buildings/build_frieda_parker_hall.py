"""Source-backed second-pass facade refinement for Frieda Parker Hall.

Run with Blender 5.2 in background mode. Only edits the Frieda asset.
The GIS footprint, local origin, root, scene, and collection identity remain fixed.
"""
import bpy
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
ASSET = ROOT / "modular" / "buildings" / "frieda_parker_hall.blend"
COLLECTION_NAME = "Asset_frieda_parker_hall"
PREFIX = "Frieda_R2_"

bpy.ops.wm.open_mainfile(filepath=str(ASSET))
col = bpy.data.collections[COLLECTION_NAME]

# FID 409's transformed polygon contains the east and west residential bars,
# but excludes the pre-existing NorthWing mass: 763.4 of its 778.1 m² rectangle
# lies outside the GIS ring (only 14.7 m² intersects). Remove this unsupported
# upper shell rather than forcing a global rescale or moving the assigned asset.
unsupported_north = bpy.data.objects.get("Frieda_NorthWing_Upper")
if unsupported_north is not None:
    bpy.data.objects.remove(unsupported_north, do_unlink=True)

# Idempotent rerun: remove only objects generated by this script.
for obj in list(col.objects):
    if obj.name.startswith(PREFIX):
        bpy.data.objects.remove(obj, do_unlink=True)

def material(name, color, roughness=0.28, metallic=0.0):
    m = bpy.data.materials.get(name)
    if m is None:
        m = bpy.data.materials.new(name)
    m.diffuse_color = (*color, 1.0)
    m.use_nodes = True
    bs = m.node_tree.nodes.get("Principled BSDF")
    if bs:
        bs.inputs["Base Color"].default_value = (*color, 1.0)
        bs.inputs["Roughness"].default_value = roughness
        bs.inputs["Metallic"].default_value = metallic
    return m

brick = bpy.data.materials.get("Frieda_Purdue_Red_Brick")
glass = bpy.data.materials.get("Frieda_Solar_Curtain_Glass") or material(
    "Frieda_Solar_Curtain_Glass", (0.12, 0.24, 0.29), 0.13, 0.12)
frame = material("Frieda_R2_DarkBronze_Mullions", (0.10, 0.105, 0.095), 0.3, 0.42)
window = material("Frieda_R2_Window_Glass", (0.18, 0.30, 0.35), 0.16, 0.08)
spandrel = material("Frieda_R2_Window_Spandrel", (0.36, 0.12, 0.08), 0.42)

def cube(name, loc, dims, mat, bevel=0.025):
    hx, hy, hz = (v/2 for v in dims)
    verts=[(-hx,-hy,-hz),(hx,-hy,-hz),(hx,hy,-hz),(-hx,hy,-hz),
           (-hx,-hy,hz),(hx,-hy,hz),(hx,hy,hz),(-hx,hy,hz)]
    faces=[(0,1,2,3),(4,7,6,5),(0,4,5,1),(1,5,6,2),(2,6,7,3),(3,7,4,0)]
    mesh=bpy.data.meshes.new(PREFIX+name+"_Mesh")
    mesh.from_pydata(verts, [], faces); mesh.update()
    o=bpy.data.objects.new(PREFIX+name, mesh)
    o.location=loc
    if mat: mesh.materials.append(mat)
    col.objects.link(o)
    return o

# The upper passage volume exists in the source model but is represented as solid
# brick. Architect documentation shows a glazed bridge/core above the open passage.
bridge = bpy.data.objects.get("Frieda_Breezeway_Upper_Bridge")
if bridge is not None:
    bpy.data.objects.remove(bridge, do_unlink=True)

# Rebuild clear-story glazing around the bridge envelope. Local XY ranges and
# z-floor bands are read from the existing bridge's unchanged dimensions.
x0, x1 = 4.725, 22.725
y0, y1 = -4.475, 5.525
z0, z1 = 8.0, 22.8
# Glass faces (thin planes are oriented to each side of the existing envelope).
cube("Bridge_Glass_East", (x1-0.035, (y0+y1)/2, (z0+z1)/2), (0.035, y1-y0-0.22, z1-z0-0.18), glass, 0.0)
cube("Bridge_Glass_West", (x0+0.035, (y0+y1)/2, (z0+z1)/2), (0.035, y1-y0-0.22, z1-z0-0.18), glass, 0.0)
cube("Bridge_Glass_North", ((x0+x1)/2, y1-0.035, (z0+z1)/2), (x1-x0-0.22, 0.035, z1-z0-0.18), glass, 0.0)
cube("Bridge_Glass_South", ((x0+x1)/2, y0+0.035, (z0+z1)/2), (x1-x0-0.22, 0.035, z1-z0-0.18), glass, 0.0)

# Bronze vertical curtainwall mullions and floor-line transoms. The 2.4 m rhythm
# is an architectural interpretation from official oblique/exterior photographs;
# exact curtainwall shop-drawing spacing is not published in the sources reviewed.
for y in [y0+0.3+i*2.35 for i in range(5)]:
    for x in (x0+0.045, x1-0.045):
        cube(f"Bridge_Mullion_X_{x:.2f}_{y:.2f}", (x,y,(z0+z1)/2), (0.12,0.09,z1-z0-0.12), frame, 0.012)
for x in [x0+0.3+i*2.48 for i in range(8)]:
    for y in (y0+0.045, y1-0.045):
        cube(f"Bridge_Mullion_Y_{x:.2f}_{y:.2f}", (x,y,(z0+z1)/2), (0.09,0.12,z1-z0-0.12), frame, 0.012)
for z in [8.08, 11.7, 15.4, 19.1, 22.65]:
    cube(f"Bridge_Transom_EW_{z:.2f}", ((x0+x1)/2,(y0+y1)/2,z), (x1-x0-0.12, y1-y0-0.12,0.10), frame, 0.01)

# Add discreet, repeated side-elevation windows to elevations left as blank brick
# in the baseline. This same insulated punched-opening language appears in the
# official oblique project photograph. They sit on, rather than cut through, the
# massing shell; locations are regularized because side-elevation drawings were
# not available. Window sizes are approximately 1.35 x 1.95 m.
def side_window(tag, center, dims, normal, sill):
    # Glass centered in the opening, with four shallow bronze perimeter rails.
    gx, gy, gz = center
    dx, dy = dims
    if normal == "y":
        cube(tag+"_Glass", (gx,gy,gz), (dx,0.11,dz:=1.95), window, 0.015)
        t=0.075
        for xx in (gx-dx/2,gx+dx/2): cube(tag+"_Jamb", (xx,gy-0.08,gz), (t,0.10,dz), frame, 0.01)
        for zz in (sill,gz+dz/2): cube(tag+"_Rail", (gx,gy-0.08,zz), (dx+t,0.10,t), frame, 0.01)
        cube(tag+"_Spandrel", (gx,gy-0.02,sill-0.18), (dx,0.08,0.24), spandrel, 0.01)
    else:
        cube(tag+"_Glass", (gx,gy,gz), (0.11,dy,dz:=1.95), window, 0.015)
        t=0.075
        for yy in (gy-dy/2,gy+dy/2): cube(tag+"_Jamb", (gx-0.08,yy,gz), (0.10,t,dz), frame, 0.01)
        for zz in (sill,gz+dz/2): cube(tag+"_Rail", (gx-0.08,gy,zz), (0.10,dy+t,t), frame, 0.01)
        cube(tag+"_Spandrel", (gx-0.02,gy,sill-0.18), (0.08,dy,0.24), spandrel, 0.01)

levels=[5.7,9.2,12.7,16.2,19.7]
# East wing south and north return elevations, facing away from the main entry.
for side,y in (("South",-49.62),("North",49.67)):
    for li,z in enumerate(levels):
        sill=z-0.92
        for bi,x in enumerate([7.5,11.2,14.9,18.6,21.0]):
            side_window(f"EastWing_{side}_F{li+1}_B{bi+1}",(x,y,z),(1.45,1.45),"y",sill)
# West-facing side of the two long east-wing bars.
for wing, yrange in (("South",[-47.0,-43.0,-39.0,-35.0,-31.0,-27.0,-23.0,-19.0,-15.0,-11.0,-7.0]),
                     ("North",[7.0,11.0,15.0,19.0,23.0,27.0,31.0,35.0,39.0,43.0,47.0])):
    for li,z in enumerate(levels):
        sill=z-0.92
        for bi,y in enumerate(yrange):
            side_window(f"EastWing_West_{wing}_F{li+1}_B{bi+1}",(4.57,y,z),(1.45,1.45),"x",sill)
# West-facing long elevation of the west wing.
for li,z in enumerate(levels):
    sill=z-0.92
    for bi,y in enumerate([5.4,9.0,12.6,16.2,19.8,22.2]):
        side_window(f"WestWing_West_F{li+1}_B{bi+1}",(-35.63,y,z),(1.45,1.45),"x",sill)
# South-facing elevation of the long west wing, visible from the walk.
for li,z in enumerate(levels):
    sill=z-0.92
    for bi,x in enumerate([-32.0,-27.0,-22.0,-17.0,-12.0,-7.0,-2.0,3.0]):
        side_window(f"WestWing_South_F{li+1}_B{bi+1}",(x,2.88,z),(1.45,1.45),"y",sill)
# Consolidate same-material boxes to keep the modular library efficient: these
# repeated facade parts do not need thousands of separate scene objects.
groups = {}
for obj in list(col.objects):
    if not obj.name.startswith(PREFIX) or obj.type != "MESH":
        continue
    key = obj.data.materials[0].name if obj.data.materials else "Unassigned"
    groups.setdefault(key, []).append(obj)
for mat_name, members in groups.items():
    bpy.ops.object.select_all(action="DESELECT")
    for obj in members:
        obj.select_set(True)
    bpy.context.view_layer.objects.active = members[0]
    bpy.ops.object.join()
    combined = bpy.context.view_layer.objects.active
    safe = mat_name.replace("Frieda_", "").replace(" ", "_")
    combined.name = PREFIX + "Combined_" + safe
    combined["source_note"] = "Combined source-supported visual refinement; side bay spacing is interpretive."

# Metadata is stored in the .blend for reviewers, without altering modular IDs.
for obj in col.objects:
    if obj.name.startswith(PREFIX):
        obj["source_note"] = "Facade/window refinement based on Mackey Mitchell official Frieda Parker Hall photographs; exact side elevations inferred."

bpy.ops.wm.save_as_mainfile(filepath=str(ASSET))
print(f"Saved {ASSET}; generated {sum(1 for o in col.objects if o.name.startswith(PREFIX))} refinement objects")
